INSERT OR REPLACE INTO LOTM_PathProjectRules
 SELECT r.*, 'RESOURCE_LOTM_PROJECT_GATE_' || SUBSTR(r.ProjectType,14) FROM Rules r
 JOIN Projects p ON p.ProjectType=r.ProjectType
 JOIN Modifiers m ON m.ModifierId=r.ModifierId;

-- New grants must be reversible. A database update alone does not prove that
-- serialized Permanent=1 instances in an old save have been removed.
UPDATE Modifiers SET Permanent=0
 WHERE ModifierId IN (SELECT ModifierId FROM LOTM_PathProjectRules);

-- The engine checks PrereqResource independently of AllowProject. This keeps
-- an old save's already-granted availability from bypassing current rules.
-- Bonus resources have no stockpile decay or strategic-resource upkeep; these
-- never spawn on the map. Gameplay changes only the previous/current token.
INSERT OR IGNORE INTO Types(Type,Kind)
 SELECT GateResourceType,'KIND_RESOURCE' FROM LOTM_PathProjectRules;
INSERT OR IGNORE INTO Resources(ResourceType,Name,ResourceClassType,Frequency,LakeEligible)
 SELECT GateResourceType,'LOC_LOTM_PATH_PROJECT_GATE_NAME','RESOURCECLASS_BONUS',0,0
 FROM LOTM_PathProjectRules;
UPDATE Projects SET PrereqResource=(
 SELECT GateResourceType FROM LOTM_PathProjectRules r WHERE r.ProjectType=Projects.ProjectType
)
WHERE ProjectType IN (SELECT ProjectType FROM LOTM_PathProjectRules);
