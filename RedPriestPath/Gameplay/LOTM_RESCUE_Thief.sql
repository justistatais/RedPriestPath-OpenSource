FROM Projects WHERE ProjectType IN (
 'PROJECT_LOTM_TP_SWINDLER_POTION','PROJECT_LOTM_TP_CRYPTOLOGIST_POTION',
 'PROJECT_LOTM_TP_PROMETHEUS_POTION','PROJECT_LOTM_TP_DREAM_STEALER_POTION',
