-- A project completion itself grants a native, permanent player marker.
-- This avoids the requirement/free-resource extraction chain, which remained
-- zero after actual completions in resource 385. No Lua attachment or UI
-- assertion can grant this marker. Existing saves without it are not migrated.
CREATE TABLE IF NOT EXISTS LOTM_RESCUE_PotionCompletions(
 ProjectType TEXT PRIMARY KEY NOT NULL REFERENCES Projects(ProjectType),
 PropertyKey TEXT NOT NULL UNIQUE,
 ModifierId TEXT NOT NULL UNIQUE
);
