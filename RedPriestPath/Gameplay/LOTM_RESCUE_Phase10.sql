-- GameCore's standard VictoryManager evaluates the built-in conquest pipeline.
-- VICTORY_DEFAULT is the last-major-civilization sentinel, not the ordinary
-- single-player domination path, so it must not be repurposed for rescue.
-- Preserve the native conquest presentation assets, but prevent GameCore from
-- awarding a real conquest victory.  The rescue UI invokes the already-loaded
-- Firaxis EndGame function only after the synchronized Boss condition is met.
UPDATE Victories SET
 Name='LOC_VICTORY_LOTM_RESCUE_NAME',
 Blurb='LOC_VICTORY_LOTM_RESCUE_FINAL',
 Description='LOC_VICTORY_LOTM_RESCUE_DESCRIPTION',
 RequirementSetId='REQUIREMENTS_LOTM_RESCUE_DISABLE_NATIVE_CONQUEST',
 CriticalPercentage=100,
 OneMoreTurn=0,
 Icon='ICON_UNIT_LOTM_RP_PATH_HOLDER'
 WHERE VictoryType='VICTORY_CONQUEST';

-- This database action is gated by LOTM_RP_RESCUE_MODE in the modinfo.
-- Redemption Mode has exactly one runtime victory; ordinary games never load
-- this DELETE and retain every base-game victory unchanged.
DELETE FROM Victories
WHERE VictoryType <> 'VICTORY_CONQUEST';
