INSERT OR REPLACE INTO Modifiers(ModifierId,ModifierType,SubjectRequirementSetId,Permanent)
SELECT 'LOTM_CULT_'||e.Token||'_'||s.Sign||'__'||e.Suffix,e.ModifierType,e.RequirementSetId,1
FROM LOTM_CultEffectRows e CROSS JOIN LOTM_CultSigns s;
INSERT OR REPLACE INTO ModifierArguments(ModifierId,Name,Value)
SELECT 'LOTM_CULT_'||e.Token||'_'||s.Sign||'__'||e.Suffix,e.Arg1,
 CASE WHEN e.Arg1='Amount' THEN CAST(CAST(e.Value1 AS INTEGER)*s.Factor AS TEXT) ELSE e.Value1 END
FROM LOTM_CultEffectRows e CROSS JOIN LOTM_CultSigns s;
INSERT OR REPLACE INTO ModifierArguments(ModifierId,Name,Value)
SELECT 'LOTM_CULT_'||e.Token||'_'||s.Sign||'__'||e.Suffix,e.Arg2,
 CASE WHEN e.Arg2='Amount' THEN CAST(CAST(e.Value2 AS INTEGER)*s.Factor AS TEXT) ELSE e.Value2 END
FROM LOTM_CultEffectRows e CROSS JOIN LOTM_CultSigns s WHERE e.Arg2 IS NOT NULL;

