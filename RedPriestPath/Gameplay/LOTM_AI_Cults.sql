 Token TEXT NOT NULL, Suffix TEXT NOT NULL, ModifierType TEXT NOT NULL,
 RequirementSetId TEXT, Arg1 TEXT NOT NULL, Value1 TEXT NOT NULL,
 Arg2 TEXT, Value2 TEXT, PRIMARY KEY(Token,Suffix)
);
