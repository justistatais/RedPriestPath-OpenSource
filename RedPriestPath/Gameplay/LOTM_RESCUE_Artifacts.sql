INSERT OR IGNORE INTO Modifiers
 (ModifierId,ModifierType,RunOnce,Permanent,OwnerRequirementSetId,SubjectRequirementSetId)
SELECT modifier.ModifierId||'_RESCUE268_'||polarity.Polarity,modifier.ModifierType,0,0,
 CASE WHEN ownerMap.ArtifactType IS NULL THEN modifier.OwnerRequirementSetId
      WHEN polarity.Polarity='NEG' THEN rescue.NegativeRequirementSetId ELSE rescue.PositiveRequirementSetId END,
 CASE WHEN subjectMap.ArtifactType IS NULL THEN modifier.SubjectRequirementSetId
      WHEN polarity.Polarity='NEG' THEN rescue.NegativeRequirementSetId ELSE rescue.PositiveRequirementSetId END
FROM LOTM_ArtifactModifierPolarity81 polarity
JOIN Modifiers modifier ON modifier.ModifierId=polarity.ModifierId
JOIN LOTM_RescueArtifactLeases268 rescue ON rescue.ArtifactType=polarity.ArtifactType
LEFT JOIN LOTM_ArtifactTurnLeases76 ownerMap ON ownerMap.LegacyRequirementSetId=modifier.OwnerRequirementSetId
LEFT JOIN LOTM_ArtifactTurnLeases76 subjectMap ON subjectMap.LegacyRequirementSetId=modifier.SubjectRequirementSetId
WHERE modifier.ModifierId NOT IN (
 'LOTM_RP_ART_EMBER_FAST_PILLAGE',
 'LOTM_RP_ART_LETTER_PEACE_GOLD',
 'LOTM_RP_ART_SCRIPTURE_PRODUCTION','LOTM_RP_ART_SCRIPTURE_PEACE_PRODUCTION','LOTM_RP_ART_SCRIPTURE_WEARINESS',
 'LOTM_RP_ART_WEATHER_FOOD','LOTM_RP_ART_WEATHER_AMENITY','LOTM_RP_ART_WEATHER_FRIENDLY_MOVE',
