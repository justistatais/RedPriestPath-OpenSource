"""Generate isolated normal-mode balance SQL and selected-language overrides."""
from pathlib import Path
import xml.etree.ElementTree as ET

ROOT = Path(__file__).resolve().parents[1]
VALUES = {
    'HARD': [(20,30,2,10,10,1,3,2),(40,60,4,20,20,2,5,3),(60,90,6,30,30,3,8,4)],
    'INSANE': [(40,60,4,20,20,2,5,3),(80,120,7,35,40,3,8,5),(120,180,10,50,60,4,12,7)],
}

def quote(value):
    return 'NULL' if value is None else "'" + str(value).replace("'", "''") + "'"

def sql():
    modifiers, arguments, strings = [], [], []
    def add(mid, kind, req=None, **args):
        modifiers.append((mid, kind, req, 0))
        arguments.extend((mid,k,v) for k,v in args.items())
    for difficulty, stages in VALUES.items():
        for tier,(science,economy,combat,maintenance,food,amenities,heal,territory) in enumerate(stages,1):
            token=f'{difficulty}_T{tier}'
            for direction, sign in [('ON',1)]:
                prefix=f'LOTM_CDIFF_COMMON_{token}_{direction}__'
                for y,value in [('SCIENCE',science),('CULTURE',science),('FAITH',science),('PRODUCTION',economy),('GOLD',economy)]:
                    add(prefix+y,'MODIFIER_PLAYER_CITIES_ADJUST_CITY_YIELD_MODIFIER',YieldType='YIELD_'+y,Amount=value*sign)
                child=f'LOTM_CDIFF_UNIT_COMMON_{token}_{direction}'
                add(child,'MODIFIER_UNIT_ADJUST_COMBAT_STRENGTH',Amount=combat*sign)
                add(prefix+'COMBAT','MODIFIER_PLAYER_UNITS_ATTACH_MODIFIER','LOTM_CDIFF_REQSET_MILITARY',ModifierId=child)
                strings.append((child,'Preview','LOC_LOTM_CDIFF_PREVIEW_COMMON'))
                # New IDs bypass serialized rc390 military definitions. Keep
                # proven economy IDs/resources and share their exclusive gate.
                child_v2=f'LOTM_CDIFF_UNIT_V2_COMMON_{token}_{direction}'
                add(child_v2,'MODIFIER_UNIT_ADJUST_COMBAT_STRENGTH',Amount=combat*sign)
                add(f'LOTM_CDIFF_MILITARY_V2_COMMON_{token}_{direction}__COMBAT',
                    'MODIFIER_PLAYER_UNITS_ATTACH_MODIFIER','LOTM_CDIFF_REQSET_MILITARY_V2',ModifierId=child_v2)
                strings.append((child_v2,'Preview','LOC_LOTM_CDIFF_PREVIEW_COMMON'))
                prefix=f'LOTM_CDIFF_DEMONESS_{token}_{direction}__'
                add(prefix+'FOOD','MODIFIER_PLAYER_CITIES_ADJUST_CITY_YIELD_MODIFIER',YieldType='YIELD_FOOD',Amount=food*sign)
                add(prefix+'AMENITIES','MODIFIER_PLAYER_CITIES_ADJUST_TRAIT_AMENITY',Amount=amenities*sign)
                child=f'LOTM_CDIFF_UNIT_CHAINED_{token}_{direction}'
                add(child,'MODIFIER_UNIT_ADJUST_COMBAT_STRENGTH','LOTM_CDIFF_REQSET_OWN',Amount=territory*sign)
                add(f'LOTM_CDIFF_CHAINED_{token}_{direction}__COMBAT','MODIFIER_PLAYER_UNITS_ATTACH_MODIFIER','LOTM_CDIFF_REQSET_MILITARY',ModifierId=child)
                strings.append((child,'Preview','LOC_LOTM_CDIFF_PREVIEW_TERRITORY'))
                child_v2=f'LOTM_CDIFF_UNIT_V2_CHAINED_{token}_{direction}'
                add(child_v2,'MODIFIER_UNIT_ADJUST_COMBAT_STRENGTH','LOTM_CDIFF_REQSET_OWN',Amount=territory*sign)
                add(f'LOTM_CDIFF_MILITARY_V2_CHAINED_{token}_{direction}__COMBAT',
                    'MODIFIER_PLAYER_UNITS_ATTACH_MODIFIER','LOTM_CDIFF_REQSET_MILITARY_V2',ModifierId=child_v2)
                strings.append((child_v2,'Preview','LOC_LOTM_CDIFF_PREVIEW_TERRITORY'))
    lines=['-- Generated by Tests/generate_normal_balance.py; normal-mode action only.',
           "INSERT OR IGNORE INTO Requirements(RequirementId,RequirementType) VALUES",
           "('LOTM_CDIFF_REQ_MILITARY','REQUIREMENT_UNIT_TAG_MATCHES'),",
           "('LOTM_CDIFF_REQ_OWN','REQUIREMENT_UNIT_IN_OWNER_TERRITORY');",
           "INSERT OR IGNORE INTO RequirementArguments(RequirementId,Name,Value) VALUES ('LOTM_CDIFF_REQ_MILITARY','Tag','CLASS_ALL_COMBAT_UNITS');",
           "INSERT OR IGNORE INTO RequirementSets(RequirementSetId,RequirementSetType) VALUES ('LOTM_CDIFF_REQSET_MILITARY','REQUIREMENTSET_TEST_ALL'),('LOTM_CDIFF_REQSET_OWN','REQUIREMENTSET_TEST_ALL');",
           "INSERT OR IGNORE INTO RequirementSetRequirements VALUES ('LOTM_CDIFF_REQSET_MILITARY','LOTM_CDIFF_REQ_MILITARY'),('LOTM_CDIFF_REQSET_OWN','LOTM_CDIFF_REQ_OWN');"]
    # CLASS_ALL_COMBAT_UNITS labels abilities, with no direct native unit
    # bindings. Like the existing combat eligibility implementation, derive
    # an explicit type-tag set once at database setup from immutable stats.
    # Never use the live strength changed by this bonus to determine eligibility.
    lines += [
        "INSERT OR IGNORE INTO Tags(Tag,Vocabulary) VALUES ('CLASS_LOTM_CDIFF_MILITARY_V2','ABILITY_CLASS');",
        "INSERT OR IGNORE INTO TypeTags(Type,Tag) SELECT UnitType,'CLASS_LOTM_CDIFF_MILITARY_V2' FROM Units WHERE (Combat>0 OR RangedCombat>0) AND FormationClass NOT IN ('FORMATION_CLASS_CIVILIAN','FORMATION_CLASS_SUPPORT');",
        "INSERT OR IGNORE INTO Requirements(RequirementId,RequirementType) VALUES ('LOTM_CDIFF_REQ_MILITARY_V2','REQUIREMENT_UNIT_TAG_MATCHES');",
        "INSERT OR IGNORE INTO RequirementArguments(RequirementId,Name,Value) VALUES ('LOTM_CDIFF_REQ_MILITARY_V2','Tag','CLASS_LOTM_CDIFF_MILITARY_V2');",
        "INSERT OR IGNORE INTO RequirementSets(RequirementSetId,RequirementSetType) VALUES ('LOTM_CDIFF_REQSET_MILITARY_V2','REQUIREMENTSET_TEST_ALL');",
        "INSERT OR IGNORE INTO RequirementSetRequirements VALUES ('LOTM_CDIFF_REQSET_MILITARY_V2','LOTM_CDIFF_REQ_MILITARY_V2');",
    ]
    for table,cols,rows in [('Modifiers','ModifierId,ModifierType,SubjectRequirementSetId,Permanent',modifiers),('ModifierArguments','ModifierId,Name,Value',arguments),('ModifierStrings','ModifierId,Context,Text',strings)]:
        lines += [f'INSERT OR REPLACE INTO {table}({cols}) VALUES',',\n'.join('('+','.join(quote(v) for v in row)+')' for row in rows)+';']
    # Native owner requirements deactivate the entire former stage. These
    # zero-frequency bonus resources are internal eligibility flags, as in
    # Magician/Star governors, never map deposits or free strategic resources.
    for difficulty in VALUES:
        for tier in range(1,4):
            for slot in ['COMMON','DEMONESS','CHAINED']:
                token=f'{slot}_{difficulty}_T{tier}'
                resource='RESOURCE_LOTM_CDIFF_'+token
                req='LOTM_CDIFF_REQ_'+token; gate='LOTM_CDIFF_GATE_'+token
                lines += [
                    f"INSERT OR IGNORE INTO Types(Type,Kind) VALUES ('{resource}','KIND_RESOURCE');",
                    f"INSERT OR IGNORE INTO Resources(ResourceType,Name,ResourceClassType,Frequency,SeaFrequency,LakeEligible) VALUES ('{resource}','LOC_LOTM_CULT_DIFFICULTY_NAME','RESOURCECLASS_BONUS',0,0,0);",
                    f"INSERT OR IGNORE INTO Requirements(RequirementId,RequirementType) VALUES ('{req}','REQUIREMENT_PLAYER_HAS_RESOURCE_OWNED');",
                    f"INSERT OR IGNORE INTO RequirementArguments(RequirementId,Name,Value) VALUES ('{req}','ResourceType','{resource}');",
                    f"INSERT OR IGNORE INTO RequirementSets(RequirementSetId,RequirementSetType) VALUES ('{gate}','REQUIREMENTSET_TEST_ALL');",
                    f"INSERT OR IGNORE INTO RequirementSetRequirements VALUES ('{gate}','{req}');",
                    f"UPDATE Modifiers SET OwnerRequirementSetId='{gate}' WHERE ModifierId LIKE 'LOTM_CDIFF_{token}_ON__%';",
                ]
                if slot in ('COMMON','CHAINED'):
                    lines.append(f"UPDATE Modifiers SET OwnerRequirementSetId='{gate}' WHERE ModifierId LIKE 'LOTM_CDIFF_MILITARY_V2_{token}_ON__%';")
    # New saves must not attach an effective legacy military parent in
    # addition to V2. This zero-deposit resource is never granted by Gameplay.
    # Existing rc390 saves retain their serialized, nonmatching legacy filter;
    # do not retag it or pretend a DB UPDATE deletes the saved instance.
    retired='RESOURCE_LOTM_CDIFF_LEGACY_MILITARY_DISABLED'
    lines += [
        f"INSERT OR IGNORE INTO Types(Type,Kind) VALUES ('{retired}','KIND_RESOURCE');",
        f"INSERT OR IGNORE INTO Resources(ResourceType,Name,ResourceClassType,Frequency,SeaFrequency,LakeEligible) VALUES ('{retired}','LOC_LOTM_CULT_DIFFICULTY_NAME','RESOURCECLASS_BONUS',0,0,0);",
        "INSERT OR IGNORE INTO Requirements(RequirementId,RequirementType) VALUES ('LOTM_CDIFF_REQ_LEGACY_MILITARY_DISABLED','REQUIREMENT_PLAYER_HAS_RESOURCE_OWNED');",
        f"INSERT OR IGNORE INTO RequirementArguments(RequirementId,Name,Value) VALUES ('LOTM_CDIFF_REQ_LEGACY_MILITARY_DISABLED','ResourceType','{retired}');",
        "INSERT OR IGNORE INTO RequirementSets(RequirementSetId,RequirementSetType) VALUES ('LOTM_CDIFF_GATE_LEGACY_MILITARY_DISABLED','REQUIREMENTSET_TEST_ALL');",
        "INSERT OR IGNORE INTO RequirementSetRequirements VALUES ('LOTM_CDIFF_GATE_LEGACY_MILITARY_DISABLED','LOTM_CDIFF_REQ_LEGACY_MILITARY_DISABLED');",
        "UPDATE Modifiers SET OwnerRequirementSetId='LOTM_CDIFF_GATE_LEGACY_MILITARY_DISABLED' WHERE ModifierType='MODIFIER_PLAYER_UNITS_ATTACH_MODIFIER' AND ModifierId LIKE 'LOTM_CDIFF_%' AND ModifierId NOT LIKE 'LOTM_CDIFF_MILITARY_V2_%';",
    ]
    (ROOT/'Gameplay/LOTM_AI_Cult_Difficulty.sql').write_text('\n'.join(lines)+'\n',encoding='utf-8')

def overrides(language):
    root=ET.Element('GameData'); rows=ET.SubElement(root,'BaseGameText')
    for name in ['LOTM_RP_GameplayText.xml','LOTM_RP_ManualText.xml']:
        for row in ET.parse(ROOT/'Text'/language/name).getroot().iter('Row'):
            tag=row.get('Tag',''); value=row.findtext('Text') or ''; new=value
            if any(part in tag for part in ['RESCUE','ARTIFACT','SHOWCASE','GREATWORK']): continue
            if not (tag.startswith('LOC_LOTM_RP_') or tag.startswith('LOC_ABILITY_LOTM_RP_') or tag.startswith('LOC_LOTM_MANUAL_')): continue
            replacements={
                '攻击蛮族或非满血单位时+30':'攻击蛮族或非满血单位时+15',
                '攻击蛮族或非满血单位时战斗力+30':'攻击蛮族或非满血单位时战斗力+15',
                '同时满足两项条件也只获得一次+30':'同时满足两项条件也只获得一次+15',
                '驻扎期间+40战斗力':'驻扎期间+20战斗力',
                '驻扎期间战斗力+40':'驻扎期间战斗力+20',
                '己方所有单位+30战斗力':'己方所有单位+20战斗力',
                '立即获得2000金币':'立即获得1000金币',
                '+30 Combat Strength when attacking Barbarians or wounded units':'+15 Combat Strength when attacking Barbarians or wounded units',
                '+40 Combat Strength while fortified':'+20 Combat Strength while fortified',
                'all friendly units gain +30 Combat Strength':'all friendly units gain +20 Combat Strength',
                'gain 2000 Gold':'gain 1000 Gold',
            }
            for old,new_value in replacements.items(): new=new.replace(old,new_value)
            if tag=='LOC_LOTM_RP_PREVIEW_HUNTER_COMBAT': new=new.replace('+30','+15')
            if tag=='LOC_LOTM_RP_PREVIEW_PROVOKER_GARRISON': new=new.replace('+40','+20')
            if tag=='LOC_LOTM_RP_PREVIEW_IRONBLOOD_STRENGTH': new=new.replace('+30','+20')
            if new!=value:
                ET.SubElement(ET.SubElement(rows,'Replace',Tag=tag),'Text').text=new
    ET.indent(root,space='\t')
    path=ROOT/'Text/Selected'/f'LOTM_NormalBalance_{language}.xml'
    path.write_text('<?xml version="1.0" encoding="utf-8"?>\n'+ET.tostring(root,encoding='unicode')+'\n',encoding='utf-8')
    print(path.name,len(rows),'normal-only overrides')

if __name__=='__main__':
    sql()
    for language in ['zh_Hans_CN','en_US']: overrides(language)
