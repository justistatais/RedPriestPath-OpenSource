#!/usr/bin/env python3
"""Build configuration-selected BaseGameText packs from the source translations."""

from __future__ import annotations

from collections import OrderedDict
from pathlib import Path
import xml.etree.ElementTree as ET


ROOT = Path(__file__).resolve().parents[1]
SOURCE_NAMES = (
    "LOTM_RP_ConfigText.xml",
    "LOTM_RP_GameplayText.xml",
    "LOTM_RP_ManualText.xml",
    "LOTM_WORLD_ChurchesText.xml",
    "LOTM_AI_CultsText.xml",
    "LOTM_RESCUE_ClanRegistryText.xml",
    "LOTM_TP_ThiefText.xml",
)


def read_language(language: str) -> OrderedDict[str, str]:
    rows: OrderedDict[str, str] = OrderedDict()
    source_dir = ROOT / "Text" / language
    for name in SOURCE_NAMES:
        path = source_dir / name
        tree = ET.parse(path)
        for row in tree.getroot().iter("Row"):
            tag = row.get("Tag")
            text_node = row.find("Text")
            if not tag or text_node is None:
                continue
            value = text_node.text or ""
            if tag in rows and rows[tag] != value:
                raise ValueError(f"conflicting text for {tag} in {language}")
            rows[tag] = value
    return rows


def write_language(language: str, rows: OrderedDict[str, str]) -> Path:
    out_dir = ROOT / "Text" / "Selected"
    out_dir.mkdir(parents=True, exist_ok=True)
    path = out_dir / f"LOTM_RP_Selected_{language}.xml"

    game_data = ET.Element("GameData")
    base_text = ET.SubElement(game_data, "BaseGameText")
    base_text.append(ET.Comment(
        f" Generated from Text/{language}; do not edit this file by hand. "
    ))
    element_name = "Replace" if language == "en_US" else "Row"
    for tag, value in rows.items():
        row = ET.SubElement(base_text, element_name, {"Tag": tag})
        ET.SubElement(row, "Text").text = value

    ET.indent(game_data, space="\t")
    body = ET.tostring(game_data, encoding="unicode", short_empty_elements=False)
    path.write_text('<?xml version="1.0" encoding="utf-8"?>\n' + body + "\n", encoding="utf-8")
    return path


def main() -> None:
    zh = read_language("zh_Hans_CN")
    en = read_language("en_US")
    if tuple(zh) != tuple(en):
        missing_en = sorted(set(zh) - set(en))
        missing_zh = sorted(set(en) - set(zh))
        raise ValueError(f"translation tag mismatch: missing_en={missing_en}, missing_zh={missing_zh}")
    for language, rows in (("zh_Hans_CN", zh), ("en_US", en)):
        path = write_language(language, rows)
        print(f"wrote {path.relative_to(ROOT)} ({len(rows)} tags)")


if __name__ == "__main__":
    main()
